export function textWidth(str) {
  return str.length * 4 - 1;
}

export function drawText(ctx, str, x, y, color) {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  for (const ch of str.toUpperCase()) {
    const g = G[ch] || G['?'];
    for (let r = 0; r < 5; r++) {
      for (let c = 0; c < 3; c++) if (g[r][c] === '1') ctx.fillRect(cx + c, Math.round(y) + r, 1, 1);
    }
    cx += 4;
  }
}
